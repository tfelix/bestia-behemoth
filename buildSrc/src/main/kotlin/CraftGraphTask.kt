import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.dataformat.yaml.YAMLFactory
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Draws the crafting chains from the data that defines them, so the docs page cannot drift from the game.
 *
 * Reads `recipes.yml`, `items.yml` and `starter_kit.yml` and writes one Hugo page: a flowchart per station (what goes
 * in, what comes out), a table of every recipe with its skill and success chance, and the raw materials - the items
 * nothing makes - with whether anything in the world hands them out yet.
 *
 * Equipment is left off the flowcharts, since a few hundred gear recipes would drown the chains that feed them, but
 * it is in the tables.
 *
 * The output is meant to be copied into the docs repo (`content/docs/mechanics/crafting-chains-generated.md`); this
 * repo does not own that tree, so the task writes where it is told to and never reaches across.
 */
abstract class CraftGraphTask : DefaultTask() {

  @get:InputFile
  abstract val itemsYml: RegularFileProperty

  @get:InputFile
  abstract val recipesYml: RegularFileProperty

  @get:InputFile
  abstract val starterKitYml: RegularFileProperty

  /** The client's `items.csv`, for display names. A missing row falls back to the identifier, capitalised. */
  @get:InputFile
  abstract val itemsCsv: RegularFileProperty

  /** The server's resources: where drops, props, fishing and shops mention an item. */
  @get:InputDirectory
  abstract val resourcesDir: DirectoryProperty

  @get:OutputFile
  abstract val output: RegularFileProperty

  private class Item(val id: Long, val name: String, val level: Int, val type: String, val hasAxes: Boolean)

  private class Stack(val item: String, val amount: Int)

  private class Recipe(
    val identifier: String,
    val effect: String,
    val output: Stack?,
    val inputs: List<Stack>,
    val skill: String,
    val skillLevel: Int,
    val station: String?,
    val seconds: Double,
    val chance: Double,
  )

  @TaskAction
  fun draw() {
    val mapper = ObjectMapper(YAMLFactory())
    val items = readItems(mapper)
    val names = readNames()
    val recipes = readRecipes(mapper)
    val starters = mapper.readTree(starterKitYml.get().asFile)["blueprints"].map { it.asText() }.toSet()

    val made = recipes.mapNotNull { it.output?.item }.toSet()
    val used = recipes.flatMap { it.inputs.map { stack -> stack.item } }.toSet()
    val raw = (used - made).sorted()
    val mentions = worldMentions(raw, items)

    fun label(item: String): String {
      val level = items[item]?.level
      val name = names[item.uppercase()] ?: item.split('_').joinToString(" ") { it.replaceFirstChar(Char::uppercase) }

      return if (level == null) name else "$name (Lv. $level)"
    }

    val text = StringBuilder()
    text.appendLine("---")
    text.appendLine("title: Crafting Chains")
    text.appendLine("weight: 611")
    text.appendLine("description: Every recipe that refines or assembles a material, drawn per station. Generated.")
    text.appendLine("---")
    text.appendLine()
    text.appendLine("{{< alert context=\"warning\" text=\"Generated by `./gradlew craftGraph` from recipes.yml, items.yml and starter_kit.yml. Do not edit by hand.\" />}}")
    text.appendLine()
    text.appendLine("How to read it: a parallelogram is a raw material (a bestia drops it, or a player gathers or mines it), a")
    text.appendLine("box is something a recipe makes, and an arrow carries the amount that goes in. The rules behind the chains are")
    text.appendLine("on the [crafting chains](/docs/mechanics/crafting-chains/) page.")
    text.appendLine()

    val stations = recipes.groupBy { it.station }
    val order = listOf("FURNACE", "FORGE", "WORKBENCH", "TANNING_RACK", "LOOM", "GLASS_FURNACE", "GLASSBLOWING_BENCH")
    val sorted = stations.keys.sortedWith(compareBy({ order.indexOf(it).let { i -> if (i < 0) order.size else i } }, { it ?: "~" }))

    for (station in sorted) {
      val here = stations.getValue(station)
      text.appendLine("## ${stationTitle(station)}")
      text.appendLine()

      val chain = here.filter { recipe -> recipe.output != null && items[recipe.output.item]?.type != "EQUIP" }
      if (chain.isNotEmpty()) {
        text.appendLine("```mermaid")
        text.appendLine("graph LR")
        val declared = mutableSetOf<String>()
        fun declare(item: String) {
          if (!declared.add(item)) return
          val shape = if (item in raw) "[/\"${label(item)}\"/]" else "[\"${label(item)}\"]"
          text.appendLine("    $item$shape")
        }
        for (recipe in chain) {
          val out = recipe.output!!.item
          declare(out)
          for (input in recipe.inputs) {
            declare(input.item)
            text.appendLine("    ${input.item} -->|${input.amount}| $out")
          }
        }
        text.appendLine("```")
        text.appendLine()
      }

      text.appendLine("| Recipe | Needs | Makes | Skill | Success | Seconds | Known from the start |")
      text.appendLine("| --- | --- | --- | --- | --- | --- | --- |")
      for (recipe in here.sortedBy { it.identifier }) {
        val needs = recipe.inputs.joinToString(", ") { "${it.amount} x ${label(it.item)}" }.ifEmpty { "nothing" }
        val makes = recipe.output?.let { "${it.amount} x ${label(it.item)}" } ?: recipe.effect.lowercase().replace('_', ' ')
        val skill = "${recipe.skill.removePrefix("M_").lowercase().replace('_', ' ')} ${recipe.skillLevel}"
        val known = if (recipe.identifier in starters) "yes" else "discover"
        text.appendLine("| `${recipe.identifier}` | $needs | $makes | $skill | ${(recipe.chance * 100).toInt()}% | ${recipe.seconds} | $known |")
      }
      text.appendLine()
    }

    text.appendLine("## Raw materials")
    text.appendLine()
    text.appendLine("Items some recipe takes and no recipe makes. \"In the world\" is a search of the mob drop tables, props and fishing")
    text.appendLine("for the item, so a `no` is a material nobody can obtain yet.")
    text.appendLine()
    text.appendLine("| Material | Level | Carries craft-axes | In the world |")
    text.appendLine("| --- | --- | --- | --- |")
    for (item in raw) {
      val axes = if (items[item]?.hasAxes == true) "yes" else "no"
      val found = if (mentions[item].isNullOrEmpty()) "no" else mentions.getValue(item).joinToString(", ")
      text.appendLine("| ${label(item).substringBefore(" (Lv.")} | ${items[item]?.level ?: "?"} | $axes | $found |")
    }

    val file = output.get().asFile
    file.parentFile.mkdirs()
    file.writeText(text.toString())
    logger.lifecycle("Wrote ${recipes.size} recipes in ${stations.size} stations to ${file.absolutePath}")
  }

  private fun stationTitle(station: String?): String {
    return station?.split('_')?.joinToString(" ") { it.lowercase().replaceFirstChar(Char::uppercase) } ?: "By hand"
  }

  private fun readItems(mapper: ObjectMapper): Map<String, Item> {
    val tree = mapper.readTree(itemsYml.get().asFile)["items"]

    return tree.associate { node ->
      val name = node["item-db-name"].asText()
      name to Item(
        id = node["id"].asLong(),
        name = name,
        level = node["base-level"]?.asInt() ?: 1,
        type = node["type"].asText().uppercase(),
        hasAxes = node["craft-axes"] != null,
      )
    }
  }

  private fun readRecipes(mapper: ObjectMapper): List<Recipe> {
    fun stack(node: JsonNode) = Stack(node["item"].asText(), node["amount"].asInt())

    return mapper.readTree(recipesYml.get().asFile)["recipes"].map { node ->
      Recipe(
        identifier = node["identifier"].asText(),
        effect = node["effect"].asText(),
        output = node["output"]?.let(::stack),
        inputs = node["inputs"]?.map(::stack) ?: emptyList(),
        skill = node["skill"]["skill"].asText(),
        skillLevel = node["skill"]["level"].asInt(),
        station = node["station"]?.asText(),
        seconds = node["craftSeconds"].asDouble(),
        chance = node["baseSuccessChance"].asDouble(),
      )
    }
  }

  /** `KEY,Display Name` rows of the client's translation CSV; the multi-line descriptions are skipped. */
  private fun readNames(): Map<String, String> {
    val row = Regex("^([A-Z0-9_]+),([^\",][^\"]*)$")

    return itemsCsv.get().asFile.readLines()
      .mapNotNull { row.matchEntire(it.trimEnd('\r'))?.destructured }
      .filter { (key, _) -> !key.endsWith("_DESC") }
      .associate { (key, name) -> key to name }
  }

  /**
   * For each raw material, which kinds of resource hand it out: a mob's drop table (`item: name`), a prop that
   * yields it (`item-id: 43`) or a fishing catch (`item: name`). Plain text matching, which is all this needs.
   */
  private fun worldMentions(raw: List<String>, items: Map<String, Item>): Map<String, List<String>> {
    val root = resourcesDir.get().asFile
    val mobs = textOf(root.resolve("mob"))
    val props = textOf(root.resolve("prop-kinds.yml"))
    val fishing = textOf(root.resolve("fishing.yml"))

    return raw.associateWith { item ->
      val byName = Regex("""item:\s*${Regex.escape(item)}(?![a-z_])""")
      val byId = items[item]?.let { Regex("""item-id:\s*${it.id}(?![0-9])""") }

      listOfNotNull(
        "mobs".takeIf { byName.containsMatchIn(mobs) },
        "props".takeIf { byId != null && byId.containsMatchIn(props) },
        "fishing".takeIf { byName.containsMatchIn(fishing) },
      )
    }
  }

  private fun textOf(file: File): String {
    if (!file.exists()) return ""
    if (file.isFile) return file.readText()

    return file.walkTopDown().filter { it.isFile && it.extension in setOf("yml", "yaml") }.joinToString("\n") { it.readText() }
  }
}
