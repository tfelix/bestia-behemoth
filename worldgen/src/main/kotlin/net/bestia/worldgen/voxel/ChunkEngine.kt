package net.bestia.worldgen.voxel

/**
 * The one version number a client that only receives chunks has to agree with the server about.
 *
 * It covers the three things such a client actually does with a chunk: decode it ([RleCodec]), name the
 * materials in it ([BlockType]), and apply the removals that arrive afterwards (`ChunkPatchCodec`). Any of
 * them changing makes payloads wrong, and none is something the client can adapt to at runtime - so there is
 * nothing to gain from telling it *which* one moved. It gets one number, and if it does not match, it is out
 * of date.
 *
 * ### Why this is hand-incremented when the server's own versions are hashes
 *
 * [net.bestia.worldgen.store.PipelineVersion] hashes stage ids and the palette because it is a *cache key*:
 * forgetting to bump it there would silently serve terrain generated by a different build, and correct-by-
 * construction is the only defensible property for something with that failure mode.
 *
 * This is not a cache key. It is a compatibility statement between two independently released artefacts, one
 * of which is not built from this source tree, so it has to be a number a human can copy - a hash would
 * change on a whitespace-insensitive palette reordering that changes nothing the client can observe, and
 * would force a client release for it.
 *
 * The forgetting-to-bump risk that leaves is caught deliberately rather than structurally:
 * `ChunkStoreTest.the block palette is pinned` fails the build when [BlockType] changes, which is the point
 * at which somebody has to come here and decide.
 */
object ChunkEngine {

  /**
   * Bump on any change to [RleCodec]'s format, to `ChunkPatchCodec`'s format, or to [BlockType]'s ids, names,
   * or `solid` flag, and change the client's `ChunkEngine.Version` in the same commit.
   *
   * `BlockType.opacity` is deliberately **not** in that list. It decides how much of a sight line a material
   * stops, which is a server-side combat question the client neither receives nor renders; bumping for it
   * would force a client release for a number no client can observe.
   *
   * `BlockType.passability` is not in that list either, for the same reason: it decides what a server-side
   * pathfinder will walk into. No client receives it and none could act on it.
   *
   * ### Free until the first client release, and that has not happened yet
   *
   * This reached 6 once already, over the branch that built the palette out and then trimmed it back down -
   * worked materials, then vegetation, then graded ore, then the removal-only patch format, then trees and
   * crystals leaving the palette for props, then `DRY_GRASS` - each bump documented in a comment above this
   * field. Every one of those was a compatibility statement made to a client that did not exist yet, so it was
   * reset to 1, for the same reason [net.bestia.worldgen.core.Stage.version] was: the promise had no
   * counterparty. **From the first client release onwards it is append-only**, and the discipline above is
   * what it always was until then. The git history holds the old changelog.
   */
  const val VERSION = 1
}
