package net.bestia.worldgen.core

/**
 * The kinds of bestia a people can hold sacred. Named as zone-server's bestia kinds are, so the zone can pick a
 * species of the kind from the local habitat; worldgen knows kinds, not species.
 */
enum class BeastKind {
  BEAST, BIRD, REPTILE, AQUATIC, INSECT, PLANT, FORMLESS, ELEMENTAL, UNDEAD, DEMON, DRAGON
}
