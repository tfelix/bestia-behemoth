package net.bestia.worldgen.history

import net.bestia.worldgen.civ.SettlementChannels
import net.bestia.worldgen.core.ActorType
import net.bestia.worldgen.core.Chronicle
import net.bestia.worldgen.core.SiteKind
import net.bestia.worldgen.pipeline.StandardWorld
import net.bestia.worldgen.vector.FeatureKind
import net.bestia.worldgen.vector.PointMarker
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

/**
 * The history simulation, against a real generated world.
 *
 * A whole small world rather than a stub, because what history reads is a settlement set, and a settlement set
 * is the product of eight stages. Building one takes a fraction of a second at this size and the alternative -
 * a hand-written list of sites - would test the simulation against a world nothing would ever produce.
 */
class HistoryStageTest {

  private val generated by lazy {
    StandardWorld.build(StandardWorld.demoConfig(seed = 4_242L).copy(widthCells = 160, heightCells = 160))
  }

  private val chronicle: Chronicle get() = generated.world.chronicle

  @Test
  fun `the world has a history at all`() {
    assertTrue(chronicle.events.isNotEmpty(), "no events were logged")
    assertTrue(chronicle.civs.isNotEmpty(), "nobody founded a civilisation")
    assertTrue(
      chronicle.settlements.count { it.wasFounded } > chronicle.settlements.size / 2,
      "most settlement sites should end up settled, got " +
          "${chronicle.settlements.count { it.wasFounded }} of ${chronicle.settlements.size}"
    )
  }

  /**
   * Founding dates spread across the span rather than clustering in one decade.
   *
   * The property that broke first: expansion tested a civ's *aggregate* occupancy, so founding a settlement
   * pushed the civ back below its own threshold and the whole world came out with one city and nothing else.
   * A spread of founding dates is the cheapest observable proof that the loop is doing something over time.
   */
  @Test
  fun `settlements are founded across the centuries`() {
    val years = chronicle.settlements.filter { it.wasFounded }.map { it.foundedYear }
    assertTrue(years.size >= 4, "only ${years.size} settlements were ever founded")

    // Distinct centuries rather than the span between the first and last, because the span is one subtraction
    // over two outliers and says nothing about what happened between them. Three centuries with a founding in
    // each is the difference between a world that filled up over time and one that appeared at once.
    val centuries = years.map { it / 100 }.distinct()
    assertTrue(
      centuries.size >= 3,
      "every settlement was founded within ${centuries.size} century (years: ${years.sorted()})"
    )
  }

  @Test
  fun `every settlement marker has a history marker with the same index`() {
    val placed = generated.world.features.all()
      .filter { it.kind == FeatureKind.SETTLEMENT }
      .filterIsInstance<PointMarker>()
      .map { it.attribute(SettlementChannels.INDEX).toInt() }
      .sorted()

    val history = generated.world.features.all()
      .filter { it.kind == FeatureKind.SETTLEMENT_HISTORY }
      .filterIsInstance<PointMarker>()
      .map { it.attribute(HistoryChannels.INDEX).toInt() }
      .sorted()

    assertEquals(placed, history, "the placement and history stages disagree about which settlements exist")
    assertEquals(placed.size, chronicle.settlements.size, "the chronicle has a different count again")
  }

  /**
   * A name seed survives a round trip through a station channel.
   *
   * The one numerical hazard in the whole design: a station channel is a `Double`, so a 64-bit seed would lose
   * its low eleven bits and two places would quietly share a name. The mask in [Names] is what prevents that,
   * and this asserts the mask is actually applied - at both ends.
   */
  @Test
  fun `name seeds survive being stored in a station channel`() {
    val markers = generated.world.features.all()
      .filter { it.kind == FeatureKind.SETTLEMENT_HISTORY }
      .filterIsInstance<PointMarker>()

    for (marker in markers) {
      val index = marker.attribute(HistoryChannels.INDEX).toInt()
      val stored = marker.attribute(HistoryChannels.NAME_SEED).toLong()
      assertEquals(
        chronicle.settlements[index].nameSeed, stored,
        "settlement $index's name seed did not survive the channel"
      )
      assertTrue(stored <= Names.SEED_MASK, "seed $stored is wider than the mask allows")
    }
  }

  @Test
  fun `an artifact's chain ends somewhere a player could dig`() {
    val buried = chronicle.artifacts.filter { it.restingSite >= 0 }
    assertTrue(buried.isNotEmpty(), "no artifact was ever lost or entombed")

    for (relic in buried) {
      val site = chronicle.sites[relic.restingSite]
      assertTrue(
        site.kind == SiteKind.TOMB || site.kind == SiteKind.RUIN || site.kind == SiteKind.BATTLEFIELD,
        "artifact ${relic.index} rests in a ${site.kind}"
      )

      // And that site is a marker in the world, not only a record - otherwise the chain names a place that
      // chunk generation will never put anything at.
      val marker = generated.world.features.all()
        .filterIsInstance<PointMarker>()
        .firstOrNull {
          runCatching { it.attribute(SiteChannels.SITE).toInt() }.getOrNull() == site.index
        }
      assertNotNull(marker, "site ${site.index} has no feature, so the artifact is nowhere")
    }
  }

  @Test
  fun `a settlement's timeline names only that settlement's own events`() {
    val withHistory = chronicle.settlements.first { it.wasFounded }
    val events = chronicle.eventsOf(net.bestia.worldgen.core.Actor(ActorType.SETTLEMENT, withHistory.index))

    assertTrue(events.isNotEmpty(), "settlement ${withHistory.index} has no events at all")
    for (event in events) {
      assertTrue(
        event.actors.any { it.type == ActorType.SETTLEMENT && it.index == withHistory.index },
        "event ${event.id} came back from a query it does not belong to"
      )
    }
  }

  /**
   * Two runs of the same seed produce the same history, event for event.
   *
   * The whole simulation is keyed rolls rather than a stream precisely so this holds, and it is worth checking
   * rather than assuming: a single `HashMap` iteration or a stream draw anywhere in a two-hundred-tick loop
   * would break it, and the symptom would be a world whose ruins move between two runs of the same seed.
   */
  @Test
  fun `history is a pure function of the seed`() {
    val again = StandardWorld.build(
      StandardWorld.demoConfig(seed = 4_242L).copy(widthCells = 160, heightCells = 160)
    ).world.chronicle

    assertEquals(chronicle.events.size, again.events.size)
    for (i in chronicle.events.indices) {
      assertEquals(chronicle.events[i].year, again.events[i].year, "event $i moved in time")
      assertEquals(chronicle.events[i].detail, again.events[i].detail, "event $i says something else")
    }
    assertEquals(
      chronicle.settlements.map { it.population },
      again.settlements.map { it.population },
      "populations differ between two runs of the same seed"
    )
  }

  @Test
  fun `pruning keeps every cause it needs`() {
    val present = chronicle.events.mapTo(HashSet()) { it.id }
    for (event in chronicle.events) {
      for (cause in event.causes) {
        assertTrue(cause in present, "event ${event.id} cites pruned cause $cause")
      }
    }
    for (relic in chronicle.artifacts) {
      for (id in relic.provenance) {
        assertTrue(id in present, "artifact ${relic.index}'s chain cites pruned event $id")
      }
    }
  }
}
